"""## 8. Análisis Estadístico de la Red y la Carga"""

import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
# from google.colab import files

def analyze_trace_advanced(trace_events, num_nodes, filename="network_events_log.csv"):
    if not trace_events:
        print("No hay eventos en la traza para analizar.")
        return

    # 1. Crear DataFrame y exportar a CSV para descarga
    df = pd.DataFrame([event.split() for event in trace_events],
                      columns=['timestamp', 'source', 'destination', 'packet_size', 'packet_type'])
    df = df.astype({'timestamp': int, 'source': int, 'destination': int, 'packet_size': int})

    # Guardar y descargar el log
    df.to_csv(filename, index=False)
    print(f"--- Log de eventos generado: {filename} ---")
    # files.download(filename) # Esto disparará la descarga en tu navegador

    print("\n" + "="*50)
    print("   ANÁLISIS AVANZADO DE RED Y CUELLOS DE BOTELLA")
    print("="*50)

    # 2. Métricas de Carga y Congestión
    traffic_by_source = df.groupby('source')['packet_size'].sum()
    traffic_by_dest = df.groupby('destination')['packet_size'].sum()

    # Identificar Hotspots (Nodos con carga > 2 desviaciones estándar de la media)
    mean_load = traffic_by_source.mean()
    std_load = traffic_by_source.std()
    hotspots = traffic_by_source[traffic_by_source > (mean_load + std_load)].index.tolist()

    # 3. Visualizaciones Detalladas
    plt.figure(figsize=(20, 12))

    # A. Carga Temporal (Identificar picos de congestión)
    plt.subplot(2, 2, 1)
    temporal_load = df.groupby('timestamp')['packet_size'].sum()
    plt.plot(temporal_load.index, temporal_load.values, marker='o', color='firebrick')
    plt.fill_between(temporal_load.index, temporal_load.values, alpha=0.2, color='red')
    plt.title('Carga de Red por Ciclo de Tiempo (Picos de Congestión)')
    plt.xlabel('Timestamp (Ciclo)')
    plt.ylabel('Carga Total')

    # B. Distribución de Carga por Nodo (Balance de Carga)
    plt.subplot(2, 2, 2)
    node_load = pd.DataFrame({'Generada': traffic_by_source, 'Recibida': traffic_by_dest}).fillna(0)
    node_load.plot(kind='bar', ax=plt.gca())
    plt.title('Balance de Carga: Generada vs Recibida por Nodo')
    plt.xlabel('ID del Nodo')
    plt.ylabel('Carga (Bytes/Paquetes)')

    # C. Matriz de Tráfico (Heatmap de Cuellos de Botella)
    plt.subplot(2, 2, 3)
    traffic_matrix = pd.pivot_table(df, values='packet_size', index='source', columns='destination', aggfunc='sum', fill_value=0)
    sns.heatmap(traffic_matrix, annot=True, fmt="d", cmap="YlOrRd")
    plt.title('Mapa de Calor de Interconexión (Hotspots de Tráfico)')

    # D. Carga por Tipo de Capa (Contribución al Tráfico)
    plt.subplot(2, 2, 4)
    type_load = df.groupby('packet_type')['packet_size'].sum()
    plt.pie(type_load.values, labels=type_load.index, autopct='%1.1f%%', colors=sns.color_palette('pastel'))
    plt.title('Distribución de Carga por Capa SNN')

    plt.tight_layout()
     # plt.show())

    # 4. Informe de Diagnóstico
    print("\n--- DIAGNÓSTICO DE LA RED ---")
    print(f"Total de eventos registrados: {len(df)}")
    print(f"Nodo con mayor carga generada: {traffic_by_source.idxmax()} ({traffic_by_source.max()} unidades)")
    print(f"Nodo con mayor carga recibida: {traffic_by_dest.idxmax()} ({traffic_by_dest.max()} unidades)")

    if hotspots:
        print(f"⚠️ CUELLOS DE BOTELLA DETECTADOS en los nodos: {hotspots}")
        print("Sugerencia: Considera repartir las neuronas de estos nodos en procesadores vecinos.")
    else:
        print("✅ La carga parece estar bien balanceada entre los nodos.")

# Ejecutar el análisis
analyze_trace_advanced(generic_trace, num_nodes)