import matplotlib.pyplot as plt
import seaborn as sns
import pandas as pd

# --- Reproducibilidad ---
torch.manual_seed(42)
np.random.seed(42)

print(f"System Check -> NumPy: {np.__version__} | PyTorch: {torch.__version__}")

# Configuración de dispositivo
device = torch.device("cuda") if torch.cuda.is_available() else torch.device("cpu")
if device.type != 'cuda':
    print("ADVERTENCIA: CUDA no disponible, usando CPU. Intentando forzar detección...")
print(f"Hardware de entrenamiento: {device}")

"""## 3. Carga y Preprocesamiento de Datos (N-MNIST)"""

sensor_size = tonic.datasets.NMNIST.sensor_size
transform = tonic.transforms.Compose([
    tonic.transforms.ToFrame(sensor_size=sensor_size, n_time_bins=30),
    torch.from_numpy,
    torchvision.transforms.RandomRotation([-10, 10])
])

trainset = tonic.datasets.NMNIST(save_to='./data', train=True)
cached_trainset = tonic.DiskCachedDataset(trainset, transform=transform, cache_path='./cache/nmnist/train')

testset = tonic.datasets.NMNIST(save_to='./data', train=False)
cached_testset = tonic.DiskCachedDataset(testset, transform=transform, cache_path='./cache/nmnist/test')

batch_size = 128
trainloader = DataLoader(cached_trainset, batch_size=batch_size, shuffle=True)
testloader = DataLoader(cached_testset, batch_size=batch_size, shuffle=False)

"""## 4. Definición de la Arquitectura CSNN

En snntorch 0.9.4, cuando se usa `init_hidden=True`, la capa devuelve `(spk, mem)`. Sin embargo, si se usa de forma iterativa sin `init_hidden`, devuelve `(spk, mem)`. El error anterior sugiere que se estaban devolviendo más valores de los esperados o que la inicialización interna estaba causando conflictos.

A continuación, se define la red de forma robusta.
"""

spike_grad = surrogate.atan()
beta = 0.5

class CSNN(nn.Module):
    def __init__(self, beta, spike_grad):
        super().__init__()
        self.conv1 = nn.Conv2d(2, 12, 5)
        self.snn1 = snn.Leaky(beta=beta, spike_grad=spike_grad) # Sin init_hidden
        self.pool1 = nn.MaxPool2d(2)

        self.conv2 = nn.Conv2d(12, 32, 5)
        self.snn2 = snn.Leaky(beta=beta, spike_grad=spike_grad) # Sin init_hidden
        self.pool2 = nn.MaxPool2d(2)

        self.flatten = nn.Flatten()
        self.fc1 = nn.Linear(32*5*5, 10)
        self.snn3 = snn.Leaky(beta=beta, spike_grad=spike_grad) # Sin init_hidden

    def forward(self, x, mem1, mem2, mem3):
        # Etapa 1
        cur = self.conv1(x)
        spk1, mem1 = self.snn1(cur, mem1) # Pasamos el estado manualmente
        cur = self.pool1(spk1)

        # Etapa 2
        cur = self.conv2(cur)
        spk2, mem2 = self.snn2(cur, mem2) # Pasamos el estado manualmente
        cur = self.pool2(spk2)

        # Clasificador
        cur = self.flatten(cur)
        cur = self.fc1(cur)
        spk_out, mem3 = self.snn3(cur, mem3) # Pasamos el estado manualmente

        return spk_out, spk1, spk2, mem1, mem2, mem3

# Re-instanciar la red
net = CSNN(beta, spike_grad).to(device)

"""## 5. Entrenamiento de la SNN"""

optimizer = torch.optim.Adam(net.parameters(), lr=2e-3, betas=(0.9, 0.999))
loss_fn = SF.ce_rate_loss()

num_epochs = 1 # Reducido para demostración rápida (Mantener en 1)
num_iters = 100 # Entrenar durante 100 iteraciones para obtener pesos realistas y precisosciando Fase de Entrenamiento ---")
for epoch in range(num_epochs):
    for i, (data, targets) in enumerate(iter(trainloader)):
        data = data.float().to(device).transpose(0, 1) # (time, batch, channel, h, w)
        targets = targets.to(device)

        net.train()
        utils.reset(net) # Resetear estados de membrana para el nuevo batch

        mem1 = net.snn1.init_leaky()
        mem2 = net.snn2.init_leaky()
        mem3 = net.snn3.init_leaky()

        spk_rec = []
        for step in range(data.size(0)):
            # El forward ahora recibe y devuelve los estados de membrana
            spk_out, spk1, spk2, mem1, mem2, mem3 = net(data[step], mem1, mem2, mem3)
            spk_rec.append(spk_out)

        spk_rec = torch.stack(spk_rec)

        loss_val = loss_fn(spk_rec, targets)
        optimizer.zero_grad()
        loss_val.backward()
        optimizer.step()

        if i % 20 == 0:
            acc = SF.accuracy_rate(spk_rec, targets)
            print(f"Epoch {epoch}, Iter {i} | Loss: {loss_val.item():.2f} | Acc: {acc * 100:.2f}%")

        if i == num_iters: break

"""## 6. Configuración de Topología y Mapeo de Red Personalizable"""

# Definición de la topología de la red (ejemplo: una red de 16 nodos en malla 4x4)
num_nodes = 16 # Para una malla 4x4
connections = {}
for i in range(num_nodes):
    connections[i] = []
    # Conexiones para una malla 4x4
    if (i + 1) % 4 != 0: connections[i].append(i + 1) # Este
    if i % 4 != 0: connections[i].append(i - 1)     # Oeste
    if i + 4 < num_nodes: connections[i].append(i + 4) # Sur
    if i - 4 >= 0: connections[i].append(i - 4)     # Norte

print("Topología de red (ejemplo de conexiones):")
for node, conns in connections.items():
    print(f"Nodo {node}: {conns}")

# Mapeo de las capas de la SNN a los nodos de la red (Optimizado para malla 4x4)
# Distribuimos las capas por toda la malla para evitar hotspots en las esquinas
snn_layer_to_nodes_mapping = {
    'input': [0, 1], # Entrada distribuida
    'snn1': [2, 3, 4, 5, 6, 7], # Capa 1 distribuida en el centro
    'snn2': [8, 9, 10, 11, 12, 13, 14], # Capa 2 distribuida en el resto
    'output': [15] # Salida en el último nodo
}

print("\nMapeo de capas SNN a nodos de red:")
for layer, nodes in snn_layer_to_nodes_mapping.items():
    print(f"Capa {layer}: {nodes}")

"""## 7. Generación de Trazas de Red Genéricas"""

def generate_generic_trace(net, data_sample, snn_layer_to_nodes_mapping, connections, filename="generic_trace.txt"):
    print("Iniciando generación de traza...")
    net.eval()
    trace_events = []

    # Inicializar estados de membrana
    mem1 = net.snn1.init_leaky()
    mem2 = net.snn2.init_leaky()
    mem3 = net.snn3.init_leaky()

    print(f"Procesando {data_sample.size(0)} pasos de tiempo...")

    with torch.no_grad():
        for step in range(data_sample.size(0)):
            # Llamada a la red
            out_tuple = net(data_sample[step], mem1, mem2, mem3)
            spk_out, spk1, spk2 = out_tuple[0], out_tuple[1], out_tuple[2]
            mem1, mem2, mem3 = out_tuple[3], out_tuple[4], out_tuple[5]

            # 1. Tráfico del Sensor
            input_spikes = (data_sample[step] > 0).nonzero(as_tuple=False)
            if len(input_spikes) > 0:
                src_node = snn_layer_to_nodes_mapping['input'][0]
                for dst_node in snn_layer_to_nodes_mapping['snn1']:
                    trace_events.append(f"{step} {src_node} {dst_node} 1 input")

            # 2. Tráfico SNN1 -> SNN2
            spikes1 = (spk1 > 0).nonzero(as_tuple=False)
            for s in spikes1:
                channel_idx = s[1].item() % len(snn_layer_to_nodes_mapping['snn1'])
                src_node = snn_layer_to_nodes_mapping['snn1'][channel_idx]
                for dst_node in snn_layer_to_nodes_mapping['snn2']:
                    trace_events.append(f"{step} {src_node} {dst_node} 1 snn1")

            # 3. Tráfico SNN2 -> Output
            spikes2 = (spk2 > 0).nonzero(as_tuple=False)
            for s in spikes2:
                channel_idx = s[1].item() % len(snn_layer_to_nodes_mapping['snn2'])
                src_node = snn_layer_to_nodes_mapping['snn2'][channel_idx]
                for dst_node in snn_layer_to_nodes_mapping['output']:
                    trace_events.append(f"{step} {src_node} {dst_node} 1 snn2")

            if step % 10 == 0:
                print(f"Paso {step} completado. Eventos acumulados: {len(trace_events)}")

    with open(filename, 'w') as f:
        for event in trace_events:
            f.write(event + "\n")

    print(f"\n¡Éxito! Traza generada: {filename} con {len(trace_events)} eventos.")
    return trace_events

